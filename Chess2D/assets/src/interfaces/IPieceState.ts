import { IPieceDefinition } from './IPieceDefinition';

/**
 * Represents player color alignment.
 * 'w' = White, 'b' = Black.
 */
export type PieceColor = 'w' | 'b';

/**
 * Represents the active runtime state of a specific piece instance on the board.
 * Tracks piece identity, movement history, and custom variant parameters.
 */
export interface IPieceState {
    /**
     * Unique runtime identifier for this piece instance (e.g., 'w_rook_1').
     * Crucial for binding engine logic to visual Cocos Creator Sprite Nodes.
     */
    readonly id: string;

    /**
     * Immutable reference to the piece's movement vectors and rule properties.
     */
    readonly definition: IPieceDefinition;

    /**
     * Player color alignment ('w' for White, 'b' for Black).
     */
    readonly color: PieceColor;

    /**
     * Tracks whether the piece has moved from its initial position.
     * Required for Castling, Pawn initial double-step, and En Passant.
     */
    hasMoved: boolean;

    /**
     * Total number of moves executed by this piece during the match.
     */
    moveCount: number;

    /**
     * Optional state container for custom chess variants (e.g., HP, mana, cooldowns, elemental charges).
     */
    customState?: Record<string, unknown>;
}

/**
 * High-performance factory and inspection helpers for piece states.
 */
export class PieceStateUtils {
    private static instanceCounter = 0;

    /**
     * Creates a new instance of a piece runtime state.
     * @param definition The piece movement definition reference
     * @param color 'w' or 'b'
     * @param customId Optional explicit instance ID (autogenerated if omitted)
     */
    public static create(
        definition: IPieceDefinition,
        color: PieceColor,
        customId?: string
    ): IPieceState {
        const id = customId ?? `${color}_${definition.type}_${++PieceStateUtils.instanceCounter}`;
        return {
            id,
            definition,
            color,
            hasMoved: false,
            moveCount: 0
        };
    }

    /**
     * Creates a fast clone of a piece state.
     * Crucial for virtual move simulations (e.g., testing if a move exposes the King to check).
     */
    public static clone(state: IPieceState): IPieceState {
        return {
            id: state.id,
            definition: state.definition, // Safe as IPieceDefinition is immutable
            color: state.color,
            hasMoved: state.hasMoved,
            moveCount: state.moveCount,
            customState: state.customState ? { ...state.customState } : undefined
        };
    }

    /**
     * Returns the opposite player color.
     */
    public static getOppositeColor(color: PieceColor): PieceColor {
        return color === 'w' ? 'b' : 'w';
    }
}